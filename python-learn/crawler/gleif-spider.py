# 公司法律形态后缀词（查询回退时逐词去掉，如 PTE.LTD. 会拆成 PTE / LTD 两个词）
LEGAL_SUFFIXES = {
    "limited", "ltd", "co", "corp", "inc", "plc", "pte", "private",
    "gmbh", "sa", "bv", "srl",
}


def normalize_full_width(text):
    """全角括号/空格转半角，压缩空白"""
    text = text.replace("（", "(").replace("）", ")")
    text = text.replace("　", " ").replace("\u00a0", " ")
    return re.sub(r"\s+", " ", text).strip()


def comparable(text):
    """用于比对的归一化：小写、去掉所有标点空白"""
    text = normalize_full_width(text).lower()
    return re.sub(r"[\s.,()\[\]（）'\"\-&/]+", "", text)


def strip_legal_suffix(name):
    """去掉公司名末尾的法律形态后缀词（中文整体去除，英文逐词去除）"""
    for suffix in ("私人有限公司", "有限责任公司", "股份有限公司", "有限公司"):
        if name.endswith(suffix):
            return name[: -len(suffix)].strip()
    # 按空格/逗号/句号分词，如 "PTE.LTD." -> ["PTE", "LTD"]
    tokens = [t for t in re.split(r"[\s,.]+", normalize_full_width(name)) if t]
    while tokens and tokens[-1].lower() in LEGAL_SUFFIXES:
        tokens.pop()
    return " ".join(tokens).strip()


def core_keywords(name):
    """提取核心关键词：英文取前 3 个非后缀词，其余情况交给去后缀结果"""
    stripped = strip_legal_suffix(name)
    tokens = [t for t in normalize_full_width(stripped).split(" ") if t]
    latin = [t for t in tokens if re.match(r"^[A-Za-z0-9.]+$", t)]
    if len(latin) >= 2:  # 纯/混英文名：取前几个英文词
        return " ".join(latin[:3])
    # 中文或单一英文前缀：去掉括号内容后返回
    return re.sub(r"\(.*?\)", "", stripped).strip()


def query_fulltext(keyword):
    """调用 GLEIF fulltext 接口，返回记录列表"""
    params = {"filter[fulltext]": keyword, "page[size]": PAGE_SIZE}
    for attempt in range(3):
        try:
            resp = requests.get(BASE_URL, params=params, headers=HEADERS, timeout=TIMEOUT)
            resp.raise_for_status()
            data = resp.json()
            return data.get("data", [])
        except (requests.RequestException, ValueError) as exc:
            print(f"  [重试 {attempt + 1}/3] 请求失败: {exc}")
            time.sleep(2)
    return []


def extract_record(item):
    """从单条 API 记录中提取 LEI / 公司名称 / othername / 国家代码"""
    attrs = item["attributes"]
    entity = attrs.get("entity", {})
    other_names = "; ".join(
        f"{o.get('name', '')}({o.get('type', '')})" for o in entity.get("otherNames", [])
    )
    return {
        "lei": attrs.get("lei", ""),
        "legal_name": entity.get("legalName", {}).get("name", ""),
        "other_names": other_names,
        "country": entity.get("legalAddress", {}).get("country", ""),
    }


def match_type(keyword, record):
    """判断记录与查询名的关系：精确匹配 / 候选(模糊)"""
    target = comparable(keyword)
    names = [record["legal_name"]] + [o.split("(")[0] for o in record["other_names"].split("; ")]
    if any(target and target == comparable(n) for n in names if n):
        return "精确匹配"
    return "候选(模糊)"


def search_company(name):
    """对一家公司执行多级回退查询，返回结果行列表"""
    name_std = normalize_full_width(name)
    strategies = [name_std, strip_legal_suffix(name_std), core_keywords(name_std)]

    seen_lei = {}
    exact_found = False
    used_keyword = None
    for keyword in strategies:
        if not keyword or keyword == used_keyword:
            continue
        used_keyword = keyword
        print(f"  检索关键词: {keyword}")
        records = [extract_record(item) for item in query_fulltext(keyword)]
        for record in records:
            if record["lei"] in seen_lei:
                continue
            record["match"] = match_type(name_std, record)
            seen_lei[record["lei"]] = record
            if record["match"] == "精确匹配":
                exact_found = True
        if exact_found or seen_lei:
            break  # 已有结果即停止回退
        time.sleep(REQUEST_INTERVAL)

    rows = list(seen_lei.values())
    if exact_found:
        rows = [r for r in rows if r["match"] == "精确匹配"]
    rows = rows[:FUZZY_LIMIT]
    if not rows:
        rows = [{"lei": "", "legal_name": "", "other_names": "", "country": "", "match": "未找到"}]
    for row in rows:
        row["query"] = name
    return rows


def save_csv(rows, path):
    """结果写入 CSV（utf-8-sig 便于 Excel 直接打开）"""
    fields = ["query", "match", "lei", "legal_name", "other_names", "country"]
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def main():
    all_rows = []
    for idx, name in enumerate(COMPANIES, 1):
        print(f"[{idx}/{len(COMPANIES)}] {name}")
        rows = search_company(name)
        for row in rows:
            print(f"    {row['match']} | {row['lei']} | {row['legal_name']} | {row['country']}")
        all_rows.extend(rows)
        if idx < len(COMPANIES):
            time.sleep(REQUEST_INTERVAL)

    out_path = "gleif_result.csv"
    save_csv(all_rows, out_path)
    print(f"\n完成，共 {len(all_rows)} 行结果，已保存至 {out_path}")


if __name__ == "__main__":
    main()
